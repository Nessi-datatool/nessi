// saveAlert saves an alert to disk
func (am *AlertManager) saveAlert(alert *Alert) error {
	// Marshal alert
	alertData, err := json.MarshalIndent(alert, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal alert: %w", err)
	}

	// Write alert file
	alertPath := filepath.Join(am.dataDir, "alerts", alert.ID+".json")
	if err := os.WriteFile(alertPath, alertData, 0644); err != nil {
		return fmt.Errorf("failed to write alert file: %w", err)
	}

	return nil
}

