// AddNotification adds a notification to an alert
func (am *AlertManager) AddNotification(alertID string, notification *AlertNotification) error {
	am.mu.Lock()
	defer am.mu.Unlock()

	// Check if alert exists
	alert, ok := am.alerts[alertID]
	if !ok {
		return fmt.Errorf("alert not found: %s", alertID)
	}

	// Add notification
	alert.Notifications = append(alert.Notifications, notification)

	// Write alert to disk
	if err := am.saveAlert(alert); err != nil {
		return fmt.Errorf("failed to save alert: %w", err)
	}

	return nil
}

// SendNotification sends a notification for an alert
func (am *AlertManager) SendNotification(alertID, channel, recipient string) (*AlertNotification, error) {
	am.mu.Lock()
	defer am.mu.Unlock()

	// Check if alert exists
	alert, ok := am.alerts[alertID]
	if !ok {
		return nil, fmt.Errorf("alert not found: %s", alertID)
	}

	// Check if notifier exists
	notifier, ok := am.notifiers[channel]
	if !ok {
		return nil, fmt.Errorf("notifier not found: %s", channel)
	}

	// Send notification
	notification, err := notifier.Send(alert, recipient)
	if err != nil {
		return nil, fmt.Errorf("failed to send notification: %w", err)
	}

	// Add notification to alert
	alert.Notifications = append(alert.Notifications, notification)

	// Write alert to disk
	if err := am.saveAlert(alert); err != nil {
		return nil, fmt.Errorf("failed to save alert: %w", err)
	}

	return notification, nil
}

// loadAlerts loads alerts from disk
func (am *AlertManager) loadAlerts() error {
	alertsDir := filepath.Join(am.dataDir, "alerts")

	// Read alert files
	files, err := os.ReadDir(alertsDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("failed to read alerts directory: %w", err)
	}

	// Load each alert
	for _, file := range files {
		if file.IsDir() || filepath.Ext(file.Name()) != ".json" {
			continue
		}

		// Read alert file
		alertPath := filepath.Join(alertsDir, file.Name())
		alertData, err := os.ReadFile(alertPath)
		if err != nil {
			return fmt.Errorf("failed to read alert file: %w", err)
		}

		// Unmarshal alert
		var alert Alert
		if err := json.Unmarshal(alertData, &alert); err != nil {
			return fmt.Errorf("failed to unmarshal alert: %w", err)
		}

		// Add alert to memory
		am.alerts[alert.ID] = &alert
	}

	return nil
}

// loadRules loads rules from disk
